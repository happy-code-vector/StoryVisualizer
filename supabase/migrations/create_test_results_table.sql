-- Create test_results table
-- This table stores test generation results for the admin test feature

CREATE TABLE IF NOT EXISTS test_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type TEXT NOT NULL CHECK(type IN ('image', 'video')),
  url TEXT NOT NULL,
  prompt TEXT,
  model TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- Create indexes for better query performance
CREATE INDEX IF NOT EXISTS idx_test_results_type ON test_results(type);
CREATE INDEX IF NOT EXISTS idx_test_results_created_at ON test_results(created_at DESC);

-- Add Row Level Security (RLS) policies
ALTER TABLE test_results ENABLE ROW LEVEL SECURITY;

-- Policy: Allow all operations (admin should handle authorization at API level)
-- In production, you might want to restrict this further
CREATE POLICY "Allow all operations on test_results" ON test_results
  FOR ALL
  USING (true)
  WITH CHECK (true);
